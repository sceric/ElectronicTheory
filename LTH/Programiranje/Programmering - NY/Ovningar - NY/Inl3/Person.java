


class Person{
	
    private String name;
    private String nbr;

		
			public Person(String name,String nbr){
				
				   this.name=name;
				   this.nbr=nbr;
								
			}
			

			public String getName(){
				
				return this.name;
				
			}
			
			

			public String getNumber(){
				
				return this.nbr;
				
			}
			
	
	
}